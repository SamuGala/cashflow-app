import 'transaction.dart';

/// A movement the user enters often, offered as a one-tap fill in the quick
/// add sheet. Computed on device from the local history only.
class QuickSuggestion {
  final String categoryId;
  final String? note;
  final int amountMinor;
  final String currency;
  final int count;
  final DateTime lastDate;

  const QuickSuggestion({
    required this.categoryId,
    required this.note,
    required this.amountMinor,
    required this.currency,
    required this.count,
    required this.lastDate,
  });

  @override
  bool operator ==(Object other) =>
      other is QuickSuggestion &&
      other.categoryId == categoryId &&
      other.note == note &&
      other.amountMinor == amountMinor &&
      other.currency == currency;

  @override
  int get hashCode => Object.hash(categoryId, note, amountMinor, currency);
}

/// Movements repeated at least twice in the last [window], ranked by how
/// often and how recently they were entered. Occurrences generated by
/// recurrences are skipped: those are already automatic.
List<QuickSuggestion> quickSuggestions(
  Iterable<TransactionModel> transactions, {
  required bool isIncome,
  DateTime? now,
  Duration window = const Duration(days: 120),
  int limit = 3,
}) {
  final today = now ?? DateTime.now();
  final since = today.subtract(window);
  final groups = <String, List<TransactionModel>>{};
  for (final row in transactions) {
    if (row.isIncome != isIncome ||
        row.recurringSourceId != null ||
        row.date.isBefore(since) ||
        row.date.isAfter(today)) {
      continue;
    }
    final note = row.note?.trim() ?? '';
    final key = [
      row.categoryId,
      note.toLowerCase(),
      row.originalCurrency,
      row.originalAmountMinor,
    ].join('\u0000');
    (groups[key] ??= []).add(row);
  }
  final ranked = <(double, QuickSuggestion)>[];
  for (final rows in groups.values) {
    if (rows.length < 2) continue;
    rows.sort((a, b) => b.date.compareTo(a.date));
    final latest = rows.first;
    final ageDays = today.difference(latest.date).inDays;
    final score = rows.length + (1 - ageDays / window.inDays) * 2;
    final note = latest.note?.trim();
    ranked.add((
      score,
      QuickSuggestion(
        categoryId: latest.categoryId,
        note: note == null || note.isEmpty ? null : note,
        amountMinor: latest.originalAmountMinor,
        currency: latest.originalCurrency,
        count: rows.length,
        lastDate: latest.date,
      ),
    ));
  }
  ranked.sort((a, b) {
    final byScore = b.$1.compareTo(a.$1);
    return byScore != 0 ? byScore : b.$2.lastDate.compareTo(a.$2.lastDate);
  });
  return [for (final entry in ranked.take(limit)) entry.$2];
}
